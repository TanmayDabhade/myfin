// Writes src-tauri/python/requirements.lock: every package the bundled Python
// installs, pinned to the version in constraints.txt, with the SHA-256 of
// each wheel PyPI publishes for that version (all bundled platforms). The
// bundle installs with pip --require-hashes --no-deps, so it gets exactly
// these files or fails. Reads PyPI's JSON metadata only; nothing is run.
//
//   node scripts/lock-python.cjs
const fs = require("fs");
const path = require("path");

const SPEC = path.join(__dirname, "..", "src-tauri", "python");
const PY = "313";
const PLATFORMS = {
  "aarch64-apple-darwin": (p) => /macosx_\d+_\d+_(arm64|universal2)/.test(p),
  "x86_64-apple-darwin": (p) => /macosx_\d+_\d+_(x86_64|universal2|intel)/.test(p),
  "x86_64-pc-windows-msvc": (p) => p === "win_amd64",
  "x86_64-unknown-linux-gnu": (p) => /^(manylinux\d*_[\d_]*x86_64|manylinux_2_(\d+)_x86_64)$/.test(p) && !/musllinux/.test(p),
};
const norm = (n) => n.toLowerCase().replace(/[-_.]+/g, "-");

function pins() {
  const out = new Map();
  for (const file of ["requirements.txt", "constraints.txt"])
    for (const line of fs.readFileSync(path.join(SPEC, file), "utf8").split("\n")) {
      const m = line.replace(/#.*/, "").trim().match(/^([A-Za-z0-9_.-]+)==([^\s;]+)$/);
      if (m) out.set(norm(m[1]), { name: m[1], version: m[2] });
    }
  return out;
}

// cp313 / abi3 / pure-Python wheels this interpreter can load.
function usable(filename) {
  const [, , ...rest] = filename.replace(/\.whl$/, "").split("-");
  const [py, abi, plat] = rest.slice(-3);
  const pyOk = py.split(".").some((t) => t === `cp${PY}` || t === "py3" || /^cp3\d+$/.test(t) && abi === "abi3" && +t.slice(3) <= +PY.slice(1));
  const abiOk = abi.split(".").some((a) => a === "none" || a === "abi3" || a === `cp${PY}`);
  return pyOk && abiOk ? plat.split(".") : null;
}

(async () => {
  const want = pins();
  const lines = ["# Generated by scripts/lock-python.cjs from requirements.txt and constraints.txt.", "# Do not edit; change constraints.txt and regenerate."];
  const problems = [];
  for (const { name, version } of [...want.values()].sort((a, b) => norm(a.name).localeCompare(norm(b.name)))) {
    const res = await fetch(`https://pypi.org/pypi/${encodeURIComponent(name)}/${encodeURIComponent(version)}/json`);
    if (!res.ok) throw Error(`PyPI has no ${name} ${version} (${res.status})`);
    const meta = await res.json();
    const wheels = meta.urls.filter((u) => u.packagetype === "bdist_wheel" && !u.yanked).map((u) => ({ u, plats: usable(u.filename) })).filter((w) => w.plats);
    for (const [target, ok] of Object.entries(PLATFORMS))
      if (!wheels.some((w) => w.plats.includes("any") || w.plats.some(ok))) problems.push(`${name} ${version}: no wheel for ${target}`);
    // Dependencies that are not extras must be locked too.
    for (const req of meta.info.requires_dist || []) {
      if (/extra\s*==/.test(req)) continue;
      // Skip requirements only for older Pythons (python_version < "3.11" etc.).
      const older = req.match(/python_version\s*(<=?)\s*["']3\.(\d+)["']/);
      if (older && (older[1] === "<" ? +older[2] <= +PY.slice(1) : +older[2] < +PY.slice(1))) continue;
      const dep = norm(req.match(/^[A-Za-z0-9_.-]+/)[0]);
      if (!want.has(dep)) problems.push(`${name} needs ${req}, which is not in constraints.txt`);
    }
    lines.push(`${name}==${version} \\`, ...wheels.map((w, i) => `    --hash=sha256:${w.u.digests.sha256}${i < wheels.length - 1 ? " \\" : ""}`));
  }
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  fs.writeFileSync(path.join(SPEC, "requirements.lock"), lines.join("\n") + "\n");
  console.log(`Locked ${want.size} packages`);
})().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
