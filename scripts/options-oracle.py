# Independent reference values for the Rust options-math crate, computed with
# scipy and numpy (written separately from the Rust code, not translated from
# it). Writes src-tauri/crates/options-math/tests/oracle.txt, which the
# crate's `oracle` test reads.
#
#   src-tauri/resources/python/<target>/bin/python3 -I scripts/options-oracle.py
#
# Any Python with numpy and scipy works. The output is deterministic (fixed seed).
import math
import os
import sys

import numpy as np
from scipy.optimize import brentq
from scipy.special import ndtr
from scipy.stats import norm

rng = np.random.default_rng(20261117)
out = []


def num(x):
    """Shortest round-trip text for a float (numpy 2 scalars print as np.float64(...))."""
    return repr(float(x))


def bsm(kind, s, k, t, r, q, v):
    """Black-Scholes-Merton with continuous yield, straight from the textbook formulas."""
    phi = 1.0 if kind == 1 else -1.0
    sq = math.sqrt(t)
    d1 = (math.log(s / k) + (r - q + v * v / 2) * t) / (v * sq)
    d2 = d1 - v * sq
    eq, er = math.exp(-q * t), math.exp(-r * t)
    price = phi * (s * eq * norm.cdf(phi * d1) - k * er * norm.cdf(phi * d2))
    delta = phi * eq * norm.cdf(phi * d1)
    gamma = eq * norm.pdf(d1) / (s * v * sq)
    vega = s * eq * norm.pdf(d1) * sq
    theta = -s * eq * norm.pdf(d1) * v / (2 * sq) + phi * q * s * eq * norm.cdf(phi * d1) - phi * r * k * er * norm.cdf(phi * d2)
    rho = phi * k * t * er * norm.cdf(phi * d2)
    return price, delta, gamma, vega, theta, rho


# Normal distribution function.
for x in np.concatenate([np.linspace(-8, 8, 161), rng.uniform(-10, 10, 40)]):
    out.append(f"cdf {num(x)} {num(ndtr(x))}")

# Prices and Greeks over a wide input range.
for _ in range(400):
    kind = 1 if rng.random() < 0.5 else -1
    s = float(rng.uniform(5, 500))
    k = float(s * math.exp(rng.uniform(-0.6, 0.6)))
    t = float(rng.uniform(1 / 365, 3))
    r = float(rng.uniform(-0.01, 0.08))
    q = float(rng.uniform(0, 0.05))
    v = float(rng.uniform(0.05, 1.2))
    vals = bsm(kind, s, k, t, r, q, v)
    out.append("bsm " + " ".join(num(x) for x in (kind, s, k, t, r, q, v, *vals)))

# Implied volatility: invert with Brent on scipy prices, near-the-money only
# (where the price determines sigma well).
for _ in range(200):
    kind = 1 if rng.random() < 0.5 else -1
    s = float(rng.uniform(20, 300))
    k = float(s * math.exp(rng.uniform(-0.25, 0.25)))
    t = float(rng.uniform(7 / 365, 2))
    r = float(rng.uniform(0, 0.06))
    q = float(rng.uniform(0, 0.03))
    v = float(rng.uniform(0.08, 0.9))
    price = bsm(kind, s, k, t, r, q, v)[0]
    iv = brentq(lambda x: bsm(kind, s, k, t, r, q, x)[0] - price, 1e-4, 5, xtol=1e-14, rtol=1e-14)
    out.append("iv " + " ".join(num(x) for x in (kind, price, s, k, t, r, q, iv)))

# Realized volatility on random OHLC bars.
n = 300
close = 100 * np.exp(np.cumsum(rng.normal(0, 0.015, n)))
prev = np.concatenate([[close[0]], close[:-1]])
opn = prev * np.exp(rng.normal(0, 0.006, n))
high = np.maximum(opn, close) * np.exp(np.abs(rng.normal(0, 0.008, n)))
low = np.minimum(opn, close) * np.exp(-np.abs(rng.normal(0, 0.008, n)))
for i in range(n):
    out.append(f"bar {num(opn[i])} {num(high[i])} {num(low[i])} {num(close[i])}")


def realized(est, w):
    """Annualized vol over the last w bars (bars n-w .. n-1), numpy only."""
    sl = slice(n - w, n)
    o, h, l, c = opn[sl], high[sl], low[sl], close[sl]
    pc = close[n - w - 1 : n - 1]  # prior closes
    if est == 0:
        return np.std(np.log(c / pc), ddof=1) * math.sqrt(252)
    if est == 1:
        return math.sqrt(np.mean(np.log(h / l) ** 2) / (4 * math.log(2)) * 252)
    if est == 2:
        return math.sqrt(np.mean(0.5 * np.log(h / l) ** 2 - (2 * math.log(2) - 1) * np.log(c / o) ** 2) * 252)
    rs = np.log(h / o) * (np.log(h / o) - np.log(c / o)) + np.log(l / o) * (np.log(l / o) - np.log(c / o))
    if est == 3:
        return math.sqrt(np.mean(rs) * 252)
    kk = 0.34 / (1.34 + (w + 1) / (w - 1))
    var = np.var(np.log(o / pc), ddof=1) + kk * np.var(np.log(c / o), ddof=1) + (1 - kk) * np.mean(rs)
    return math.sqrt(var * 252)


for est in range(5):
    for w in (10, 21, 63, 252):
        out.append(f"rv {est} {w} {num(realized(est, w))}")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src-tauri", "crates", "options-math", "tests", "oracle.txt")
with open(path, "w") as f:
    f.write("# Generated by scripts/options-oracle.py with scipy " + __import__("scipy").__version__ + " and numpy " + np.__version__ + ". Do not edit.\n")
    f.write("\n".join(out) + "\n")
print(f"wrote {len(out)} lines to {os.path.normpath(path)}", file=sys.stderr)
